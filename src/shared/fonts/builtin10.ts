// Pre-bake glyph rows to numeric grids so the render path is just an array
// lookup instead of charCodeAt() per pixel per frame.
const GLYPH_BITS: Record<string, number[][]> = {};
for (const [ch, rows] of Object.entries(GLYPHS)) {
  const grid: number[][] = [];
  for (let r = 0; r < FONT_H; r++) {
    const row = rows[r] ?? '';
    const line: number[] = new Array(FONT_W);
    for (let c = 0; c < FONT_W; c++) line[c] = row.charCodeAt(c) === 35 /* '#' */ ? 1 : 0;
    grid.push(line);
  }
  GLYPH_BITS[ch] = grid;
}

const FALLBACK = GLYPH_BITS['?'] ?? GLYPHS[' '].map(() => new Array(FONT_W).fill(0));

/** Look up a glyph (uppercased). Falls back to '?' for unknown chars. */
export function getGlyph(ch: string): number[][] {
  const key = ch.length === 1 ? ch.toUpperCase() : ch;
  return GLYPH_BITS[key] ?? FALLBACK;
}

export function hasGlyph(ch: string): boolean {
  const key = ch.length === 1 ? ch.toUpperCase() : ch;
  return key in GLYPH_BITS;
}
